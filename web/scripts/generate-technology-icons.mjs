import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import * as icons from 'react-icons/si';

// One shared SVG sprite avoids repeating complex paths in HTML and RSC payloads.
const technologies = [
  ['HTML', 'html', 'SiHtml5'], ['CSS', 'css', 'SiCss'],
  ['Tailwind CSS', 'tailwind', 'SiTailwindcss'], ['JavaScript', 'javascript', 'SiJavascript'],
  ['TypeScript', 'typescript', 'SiTypescript'], ['Next.js', 'next', 'SiNextdotjs'],
  ['React.js', 'react', 'SiReact'], ['Supabase', 'supabase', 'SiSupabase'],
  ['MongoDB', 'mongodb', 'SiMongodb'], ['Python', 'python', 'SiPython'],
  ['Node.js', 'node', 'SiNodedotjs'], ['PostgreSQL', 'postgresql', 'SiPostgresql'],
];
const symbols = technologies.map(([, id, exportName]) => {
  const svg = renderToStaticMarkup(createElement(icons[exportName]));
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  if (!viewBox) throw Error('Icon has no viewBox: ' + exportName);
  const children = svg.slice(svg.indexOf('>') + 1, svg.lastIndexOf('</svg>'));
  return '<symbol id="' + id + '" viewBox="' + viewBox + '" fill="currentColor">' + children + '</symbol>';
}).join('');
const sprite = '<svg xmlns="http://www.w3.org/2000/svg">' + symbols + '</svg>\n';
const hash = createHash('sha256').update(sprite).digest('hex').slice(0, 10);
const file = 'technologies.' + hash + '.svg';
await mkdir(new URL('../public/icons/', import.meta.url), { recursive: true });
await writeFile(new URL('../public/icons/' + file, import.meta.url), sprite);
await writeFile(new URL('../src/data/technology-icons.ts', import.meta.url),
  '// Generated by pnpm icons:generate.\nexport const technologySprite = ' + JSON.stringify('/icons/' + file) + ';\n' +
  'export const technologySymbols: Readonly<Record<string, string>> = ' + JSON.stringify(Object.fromEntries(technologies.map(([name, id]) => [name, id])), null, 2) + ';\n');
console.log('Technology sprite generated:', file, Buffer.byteLength(sprite), 'bytes');
